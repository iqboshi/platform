function port(key: string, label: string, dataTypes: WorkflowNodeCatalogItem['inputs'][number]['dataTypes']) {
  return { key, label, dataTypes };
}

function param(
  key: string,
  label: string,
  fieldType: WorkflowNodeCatalogItem['params'][number]['fieldType'],
  extra: Partial<Omit<WorkflowNodeCatalogItem['params'][number], 'key' | 'label' | 'fieldType'>> = {},
) {
  return { key, label, fieldType, ...extra };
}

function starter(
  inputKind: NonNullable<WorkflowNodeCatalogItem['starterBindings']>[number]['inputKind'],
  paramKey: string,
  extra: Partial<Omit<NonNullable<WorkflowNodeCatalogItem['starterBindings']>[number], 'inputKind' | 'paramKey'>> = {},
) {
  return { inputKind, paramKey, ...extra };
}

function usage(
  target: NonNullable<WorkflowNodeCatalogItem['outputBehaviors']>[number]['usages'][number]['target'],
  inputKind: NonNullable<WorkflowNodeCatalogItem['outputBehaviors']>[number]['usages'][number]['inputKind'],
) {
  return { target, inputKind };
}

function behavior(
  portKey: string,
  previewKinds: NonNullable<WorkflowNodeCatalogItem['outputBehaviors']>[number]['previewKinds'],
  usages: NonNullable<WorkflowNodeCatalogItem['outputBehaviors']>[number]['usages'],
) {
  return { portKey, previewKinds, usages };
}

function contract(
  portKey: string,
  summary: string,
  extra: Partial<
    Omit<NonNullable<WorkflowNodeCatalogItem['inputContracts']>[number], 'portKey' | 'summary'>
  > = {},
) {
  return {
    portKey,
    summary,
    datasetKinds: [],
    fileFormats: [],
    columnRequirements: [],
    sampleColumns: [],
    producedColumns: [],
    taskTypes: [],
    annotationKinds: [],
    sampleKinds: [],
    valueTypes: [],
    notes: [],
    ...extra,
  };
}

